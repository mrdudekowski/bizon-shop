import pg from "pg";
const c = new pg.Client({ host: "127.0.0.1", port: 5432, user: "postgres", password: "8955", database: "bizon" });
await c.connect();
const tires = await c.query(`SELECT tm.slug, tm.main_image_id, m.filename, m.url FROM tire_models tm LEFT JOIN media m ON m.id = tm.main_image_id WHERE tm.status = 'published'`);
console.log("tires:", JSON.stringify(tires.rows));
const wheels = await c.query(`SELECT wm.slug, wm.main_image_id, m.filename, m.url FROM wheel_models wm LEFT JOIN media m ON m.id = wm.main_image_id WHERE wm.status = 'published'`);
console.log("wheels:", JSON.stringify(wheels.rows));
const gallery = await c.query(`SELECT count(*)::int AS n FROM wheel_models_rels`);
console.log("wheel gallery rels:", gallery.rows[0].n);
await c.end();
